def superellipse(cx, cy, rx, ry, n=4.0, k=64):
    t = np.linspace(0.0, 2.0 * np.pi, k, endpoint=False)
    c, s = np.cos(t), np.sin(t)
    return np.column_stack([cx + rx * np.sign(c) * np.abs(c) ** (2.0 / n),
                            cy + ry * np.sign(s) * np.abs(s) ** (2.0 / n)])


def rounded_rect(x0, x1, z0, z1, r, k=6):
    out = []
    for cx, cz, a0 in ((x1 - r, z1 - r, 0.0), (x0 + r, z1 - r, 90.0), (x0 + r, z0 + r, 180.0),
                       (x1 - r, z0 + r, 270.0)):
        for i in range(k + 1):
            a = np.radians(a0 + 90.0 * i / k)
            out.append((cx + r * np.cos(a), cz + r * np.sin(a)))
    return np.array(out)


def ellipse(cx, cy, rx, ry, k=40):
    t = np.linspace(0.0, 2.0 * np.pi, k, endpoint=False)
    return np.column_stack([cx + rx * np.cos(t), cy + ry * np.sin(t)])


